/**
 * A WITHDRAWN PAGE ANSWERS 410, AND THE PAGES THAT ARE STILL LIVE DO NOT.
 *
 * The second half is the one that would hurt. A handler that matches too
 * greedily would take a published post off the site to fix a reporting
 * problem, which is a far worse outcome than the problem.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const TMP = fs.mkdtempSync(path.join(os.tmpdir(), "etablix-retired-"));
process.env.ETABLIX_DATA_DIR = TMP;

const { retiredUrls, retiredSlugs, retiredPaths } = await import("../lib/retired-urls.js");
const { RETIRED, POSTS } = await import("../lib/blog.js");

let pass = 0, fail = 0;
const ok = (c, m, saw) => {
  if (c) { pass++; console.log(`  ✓ ${m}`); }
  else { fail++; console.log(`  ✗ ${m}${saw !== undefined ? `\n      saw: ${saw}` : ""}`); }
};

/** Drive the middleware without starting a server. */
function call(pathname, method = "GET") {
  const handler = retiredUrls();
  const res = {
    statusCode: 200, headers: {}, body: "", ended: false,
    status(c) { this.statusCode = c; return this; },
    set(k, v) { this.headers[String(k).toLowerCase()] = v; return this; },
    type(t) { this.headers["content-type"] = t; return this; },
    send(b) { this.body = b; this.ended = true; return this; },
    end() { this.ended = true; return this; },
  };
  let passedThrough = false;
  handler({ method, path: pathname }, res, () => { passedThrough = true; });
  return { res, passedThrough };
}

console.log("\n=== the withdrawn post is gone, permanently and explicitly ===\n");
{
  ok(RETIRED.length > 0, `${RETIRED.length} post(s) are retired in the schedule`);
  ok(retiredSlugs().has("ai-agents-in-construction"),
     "the AI agents post is among them — published 10 Sep 2026, retired 13 Oct 2026");

  for (const p of ["/blog/ai-agents-in-construction", "/blog/ai-agents-in-construction/", "/blog/ai-agents-in-construction.html"]) {
    const { res, passedThrough } = call(p);
    ok(!passedThrough, `${p} is handled here, not passed to the file server`);
    ok(res.statusCode === 410, `  and answers 410 Gone, not 404`, res.statusCode);
  }

  const { res } = call("/blog/ai-agents-in-construction");
  ok(res.headers["x-robots-tag"] === "noindex", "it is marked noindex as well as gone");
  ok(/withdrawn/i.test(res.body), "the page says it was withdrawn");
  ok(!/coming back|republish|restore/i.test(res.body),
     "and does not suggest it might return", res.body.slice(0, 160));

  /**
   * THE CONTENT RULE THIS EXISTS TO SERVE. The post was removed because
   * nothing a customer reads may describe this work as generated by AI. The
   * replacement page is read by customers, so it must not reintroduce the
   * subject it was written to remove.
   */
  ok(!/\bAI\b|artificial intelligence|agent/i.test(res.body),
     "and the replacement page does not mention AI or agents at all", res.body.slice(0, 200));
}

console.log("\n=== HEAD is answered too, because crawlers use it ===\n");
{
  const { res } = call("/blog/ai-agents-in-construction", "HEAD");
  ok(res.statusCode === 410, "HEAD gets the same 410", res.statusCode);
  ok(res.body === "", "with no body", JSON.stringify(res.body));
}

console.log("\n=== nothing that is still live is touched ===\n");
{
  ok(POSTS.length > 0, `${POSTS.length} post(s) are published`);
  for (const p of POSTS) {
    const { passedThrough } = call(`/blog/${p.slug}`);
    ok(passedThrough, `/blog/${p.slug} is still served normally`);
  }
  for (const p of ["/blog", "/blog/", "/", "/index.html", "/contact", "/services"]) {
    const { passedThrough } = call(p);
    ok(passedThrough, `${p} is untouched`);
  }
  // A slug that looks similar must not be swallowed.
  const { passedThrough } = call("/blog/ai-agents-in-construction-two");
  ok(passedThrough, "a different slug with the same prefix is not caught");
}

console.log("\n=== a write is never answered with a 410 page ===\n");
{
  for (const m of ["POST", "PUT", "DELETE"]) {
    const { passedThrough } = call("/blog/ai-agents-in-construction", m);
    ok(passedThrough, `${m} passes through rather than being answered here`);
  }
}

console.log("\n=== the list is data, not code ===\n");
{
  const schedule = JSON.parse(fs.readFileSync(path.resolve(
    path.dirname(new URL(import.meta.url).pathname), "..", "..", "content", "blog", "schedule.json"), "utf8"));
  const retiredInFile = Object.entries(schedule).filter(([k, v]) => k !== "_note" && v && v.retired).map(([k]) => k);
  ok(retiredInFile.length === retiredSlugs().size,
     "every retired entry in schedule.json is handled, and nothing else is",
     `${retiredInFile.join(",")} vs ${[...retiredSlugs()].join(",")}`);

  const src = fs.readFileSync(path.resolve(
    path.dirname(new URL(import.meta.url).pathname), "..", "lib", "retired-urls.js"), "utf8");
  ok(!/ai-agents-in-construction/.test(src),
     "and no slug is hard-coded in the handler, so retiring the next post needs no code change");

  ok(retiredPaths().size === retiredSlugs().size * 3,
     "three addresses are covered per retired post: bare, trailing slash, and .html");
}

fs.rmSync(TMP, { recursive: true, force: true });
console.log(`\n=== ${pass} passed, ${fail} failed ===\n`);
process.exit(fail ? 1 : 0);
